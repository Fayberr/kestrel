    /**
     * Vanilla's own writer, {@code SerializableChunkData.packOffsets} (private,
     * reached reflectively), against {@code ChunkCodec}'s tag, byte for byte,
     * and Kestrel's reader over vanilla's bytes.
     */
    private static void checkVanillaEncoding(KestrelLevel level, List<Long> keys, int sectionCount)
            throws Exception {
        Method packOffsets = net.minecraft.world.level.chunk.storage.SerializableChunkData.class
                .getDeclaredMethod("packOffsets", ShortList[].class);
        packOffsets.setAccessible(true);
        dev.kestrel.persist.WorldSnapshot snapshot =
                dev.kestrel.persist.WorldSnapshot.capture(new TickLoop(level));
        for (long key : keys) {
            ShortList[] lists = level.postProcessing(key);
            ShortList[] vanillaInput = new ShortList[sectionCount];
            if (lists != null) {
                for (int i = 0; i < sectionCount; i++) {
                    vanillaInput[i] = lists[i] == null ? null : new ShortArrayList(lists[i]);
                }
            }
            CompoundTag vanilla = new CompoundTag();
            vanilla.put("PostProcessing", (ListTag) packOffsets.invoke(null, (Object) vanillaInput));
            ByteArrayOutputStream vanillaBytes = new ByteArrayOutputStream();
            NbtIo.write(vanilla, new DataOutputStream(vanillaBytes));

            Nbt.Tag.TCompound kestrel = Nbt.compound();
            Nbt.put(kestrel, "PostProcessing", Nbt.getOrNull(ChunkCodec.encodeChunk(snapshot,
                    ChunkPos.getX(key), ChunkPos.getZ(key)), "PostProcessing"));
            byte[] kestrelBytes = Nbt.encodeRoot(kestrel);
            check(Arrays.equals(vanillaBytes.toByteArray(), kestrelBytes),
                    "ChunkCodec writes PostProcessing byte-equal to vanilla for " + key(key));

            CompoundTag readBack = new CompoundTag();
            readBack.putInt("xPos", ChunkPos.getX(key));
            readBack.putInt("zPos", ChunkPos.getZ(key));
            readBack.put("PostProcessing", vanilla.get("PostProcessing"));
            ByteArrayOutputStream readBytes = new ByteArrayOutputStream();
            NbtIo.write(readBack, new DataOutputStream(readBytes));
            ChunkCodec.DecodedChunk decoded = ChunkCodec.decodeChunk(
                    Nbt.decodeRoot(new DataInputStream(new ByteArrayInputStream(readBytes.toByteArray()))),
                    level.getMinY(), level.getHeight(), 0L);
            check(sameLists(toLists(decoded.postProcessing()), lists),
                    "ChunkCodec reads vanilla's PostProcessing back for " + key(key));
        }
    }

