    /**
     * A detached copy of a generated chunk: its sections, its pending
     * post-processing, fresh (empty) tick containers, sky-light sources
     * recomputed from the copied sections, status LIGHT.
     */
    private static ProtoChunk copy(HeadlessNoise.Driver driver, ProtoChunk source) {
        LevelChunkSection[] from = source.getSections();
        LevelChunkSection[] sections = new LevelChunkSection[from.length];
        for (int i = 0; i < from.length; i++) {
            sections[i] = from[i].copy();
        }
        ProtoChunk copy = new ProtoChunk(source.getPos(), UpgradeData.EMPTY, sections,
                new ProtoChunkTicks<>(), new ProtoChunkTicks<>(), driver.height(),
                HeadlessNoise.factory(driver.access()), null);
        ShortList[] marks = source.getPostProcessing();
        for (int i = 0; i < marks.length; i++) {
            if (marks[i] != null && !marks[i].isEmpty()) {
                copy.addPackedPostProcess(new ShortArrayList(marks[i]), i);
            }
        }
        copy.setPersistedStatus(ChunkStatus.LIGHT);
        copy.initializeLightSources();
        return copy;
    }

    /**
     * A vanilla engine over the chunks, lit from scratch the way
     * {@code ThreadedLevelLightEngine} runs INITIALIZE_LIGHT then LIGHT for
     * freshly generated chunks.
     */
    private static LevelLightEngine litEngine(HeadlessNoise.Driver driver,
            Map<Long, ? extends ChunkAccess> chunks) {
        LevelLightEngine engine = new LevelLightEngine(getter(driver, chunks), true,
                driver.dimensionType().value().hasSkyLight());
        for (ChunkAccess chunk : chunks.values()) {
            LevelChunkSection[] sections = chunk.getSections();
            for (int i = 0; i < chunk.getSectionsCount(); i++) {
                if (!sections[i].hasOnlyAir()) {
                    engine.updateSectionStatus(SectionPos.of(chunk.getPos(),
                            chunk.getSectionYFromSectionIndex(i)), false);
                }
            }
        }
        engine.runLightUpdates();
        for (ChunkAccess chunk : chunks.values()) {
            engine.setLightEnabled(chunk.getPos(), false);
            engine.retainData(chunk.getPos(), false);
        }
        for (ChunkAccess chunk : chunks.values()) {
            engine.propagateLightSources(chunk.getPos());
        }
        engine.runLightUpdates();
        return engine;
    }

