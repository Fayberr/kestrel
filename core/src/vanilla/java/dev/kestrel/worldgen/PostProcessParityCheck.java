    /** True when every chunk within {@code radius} of (cx, cz) is in {@code done}. */
    private static boolean complete(Set<Long> done, int cx, int cz, int radius) {
        for (int dx = -radius; dx <= radius; dx++) {
            for (int dz = -radius; dz <= radius; dz++) {
                if (!done.contains(ChunkPos.pack(cx + dx, cz + dz))) {
                    return false;
                }
            }
        }
        return true;
    }

    private static boolean sameLists(ShortList[] a, ShortList[] b) {
        return Arrays.deepEquals(normalize(a), normalize(b));
    }

    private static short[][] normalize(ShortList[] lists) {
        if (lists == null) {
            return new short[0][];
        }
        List<short[]> out = new ArrayList<>();
        boolean any = false;
        for (ShortList list : lists) {
            short[] values = list == null ? new short[0] : list.toShortArray();
            any |= values.length > 0;
            out.add(values);
        }
        return any ? out.toArray(new short[0][]) : new short[0][];
    }

    private static ShortList[] toLists(short[][] sections) {
        if (sections == null) {
            return null;
        }
        ShortList[] lists = new ShortList[sections.length];
        for (int i = 0; i < sections.length; i++) {
            lists[i] = sections[i].length == 0 ? null : new ShortArrayList(sections[i]);
        }
        return lists;
    }

    private static String write(BlockPos pos, BlockState state, int flags) {
        return pos.toShortString() + " " + state + " flags=" + flags;
    }

    private static String tick(BlockPos pos, Object type, long trigger, int priority) {
        return pos.toShortString() + " " + type + " at=" + trigger + " priority=" + priority;
    }

    private static String firstDifference(List<String> a, List<String> b) {
        for (int i = 0; i < Math.max(a.size(), b.size()); i++) {
            String x = i < a.size() ? a.get(i) : "<none>";
            String y = i < b.size() ? b.get(i) : "<none>";
            if (!x.equals(y)) {
                return "; first difference at " + i + ": kestrel " + x + " vanilla " + y;
            }
        }
        return "";
    }

    private static String key(long key) {
        return ChunkPos.getX(key) + "," + ChunkPos.getZ(key);
    }

    private static String keys(Set<Long> keys) {
        List<String> out = new ArrayList<>();
        for (long key : keys) {
            out.add(key(key));
        }
        out.sort(Comparator.naturalOrder());
        return out.toString();
    }

    private static void deleteTree(Path root) throws java.io.IOException {
        try (var walk = Files.walk(root)) {
            for (Path p : walk.sorted(Comparator.reverseOrder()).toList()) {
                Files.delete(p);
            }
        }
    }

    private static void check(boolean condition, String label) {
        checks++;
        if (!condition) {
            throw new AssertionError(label);
        }
    }
