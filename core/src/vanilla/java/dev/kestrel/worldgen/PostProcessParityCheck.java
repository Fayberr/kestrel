    /** Every stored value of both layers in every light section of the compared chunks. */
    private static long compareLight(LevelLightEngine kestrel, LevelLightEngine vanilla, Set<Long> compared,
            String when) {
        long values = 0;
        int minSection = kestrel.getMinLightSection();
        int maxSection = kestrel.getMaxLightSection();
        for (long chunkKey : compared) {
            int cx = ChunkPos.getX(chunkKey);
            int cz = ChunkPos.getZ(chunkKey);
            {
                for (int sy = minSection; sy < maxSection; sy++) {
                    SectionPos section = SectionPos.of(cx, sy, cz);
                    for (LightLayer layer : LightLayer.values()) {
                        DataLayer k = kestrel.getLayerListener(layer).getDataLayerData(section);
                        DataLayer v = vanilla.getLayerListener(layer).getDataLayerData(section);
                        if ((k == null) != (v == null)) {
                            check(false, layer + " light layer presence differs " + when + " at section "
                                    + cx + "," + sy + "," + cz + ": kestrel " + (k != null)
                                    + " vanilla " + (v != null));
                            continue;
                        }
                        if (k == null) {
                            continue;
                        }
                        if (!Arrays.equals(k.getData(), v.getData())) {
                            for (int i = 0; i < 4096; i++) {
                                int x = i & 15;
                                int z = (i >> 4) & 15;
                                int y = i >> 8;
                                if (k.get(x, y, z) != v.get(x, y, z)) {
                                    check(false, layer + " light differs " + when + " at "
                                            + ((cx << 4) + x) + "," + ((sy << 4) + y) + "," + ((cz << 4) + z)
                                            + ": kestrel " + k.get(x, y, z) + " vanilla " + v.get(x, y, z));
                                }
                            }
                        }
                        values += 4096;
                    }
                }
            }
        }
        checks++;
        return values;
    }

