#!/usr/bin/env python3
"""Kestrel benchmark runner: drives harness/bench.yaml end to end.

Reads bench.yaml, generates a single self-contained PowerShell script that
runs the full servers x flag_sets x scenarios x repeats matrix on the target
machine, launches it DETACHED (survives SSH disconnect), and exits. Progress
lands in the results file; poll it with:

  python3 run-bench.py --poll

Usage:
  python3 run-bench.py [--only crowd] [--bots 10] [--repeats 3] [--stay 120]
      [--servers vanilla,kestrel] [--flags tuned] [--mode quality] [--launch]

  --launch   copy scripts + launch detached on the bench PC, then exit.
  (default without --launch: regenerate scripts locally only, dry run.)

The generated bench_run.ps1 replaces bench_one.ps1/bench_all.ps1/benchfull.ps1
(they stay on the bench PC but are no longer used).
"""

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime

try:
    import yaml
except ImportError:
    sys.exit("need pyyaml: pip install pyyaml")

# SSH target of the Windows bench machine, e.g. KESTREL_BENCH_HOST=me@192.0.2.10
WINPC = os.environ.get("KESTREL_BENCH_HOST", "user@bench-pc")
BENCH_DIR = r"C:\Users\bench\bench"

PS_TEMPLATE = r'''
# AUTO-GENERATED by run-bench.py {stamp}. Do not hand-edit; edit bench.yaml.
param([string]$Only = "", [string]$Servers = "", [string]$Flags = "", [string]$BotOverride = "", [string]$RepeatOverride = "", [string]$StayOverride = "")
# Failures inside a run block are caught per-block as RESULT ERROR so one
# bad run cannot kill the matrix; best-effort lines keep SilentlyContinue.
$ErrorActionPreference = 'Stop'
$OUT = '{results_file}'
$JSON = '{json_file}'
$cores = [int]$env:NUMBER_OF_PROCESSORS
function Log($m) {{ Add-Content $OUT ("[{{0}}] {{1}}" -f (Get-Date -Format 'HH:mm:ss'), $m) }}
# Append-only results: a second launch (or the WI-8 child log) never wipes
# rows already collected; the header marks each matrix start instead.
Add-Content $OUT ("benchmark started {{0}} only={{1}} servers={{2}} flags={{3}} bots={{4}} reps={{5}} stay={{6}}" -f (Get-Date -Format 'HH:mm:ss'), $Only, $Servers, $Flags, $BotOverride, $RepeatOverride, $StayOverride)
Log ("build {{0}} | script {{1}} | flags {{2}}" -f '{build_id}', '{script_map}', '{flag_map}')
$summary = @()
# Incremental JSON: each valid run rewrites the file, so a killed matrix
# keeps the completed rows (previously written once at the very end).
function SaveJson {{ $summary | ConvertTo-Json -Depth 4 | Set-Content $JSON }}
{run_blocks}
Add-Content $OUT ("benchmark finished {{0}}" -f (Get-Date -Format 'HH:mm:ss'))
SaveJson
'''

RUN_BLOCK = r'''
# ---- {tag} ----
# -Only/-Servers/-Flags accept comma lists.
if ((($Only -split ',') -contains "{scenario}" -or $Only -eq "") -and ((($Servers -split ',')) -contains "{server}" -or $Servers -eq "") -and ((($Flags -split ',')) -contains "{flag}" -or $Flags -eq "")) {{
$repN = {repeats}; if ($RepeatOverride -ne "") {{ $repN = [int]$RepeatOverride }}
$repResults = @()
for ($rep = 1; $rep -le $repN; $rep++) {{
$rtag = "{tag}#r$rep"
try {{
Log "$rtag : launching (attempt loop)..."
$attempt = 0; $ok = $false; $proc = $null
while (-not $ok -and $attempt -le {retries}) {{
  $attempt++
  $before = Get-Process | Where-Object {{ $_.ProcessName -match '^(kjava|java)$' }} | Select-Object -ExpandProperty Id
  Remove-Item '{log}' -ErrorAction SilentlyContinue
  $boot0 = Get-Date
  Start-Process -FilePath 'cmd.exe' -ArgumentList "/c `"{script}`"" -WindowStyle Hidden
  for ($i = 0; $i -lt {ready_timeout}; $i++) {{
    Start-Sleep -Seconds 1
    if (Test-Path '{log}') {{
      if (Select-String -Path '{log}' -Pattern '{pattern}' | Select-Object -First 1) {{ $ok = $true; break }}
    }}
  }}
  if (-not $ok) {{
    Log "$rtag : boot attempt $attempt NOT-READY, killing leftovers..."
    $afterFail = Get-Process | Where-Object {{ $_.ProcessName -match '^(kjava|java)$' }} | Select-Object -ExpandProperty Id
    $leftover = $afterFail | Where-Object {{ $before -notcontains $_ }}
    foreach ($lid in $leftover) {{ Stop-Process -Id $lid -Force }}
    Start-Sleep -Seconds 3
  }}
}}
if (-not $ok) {{ Log "$rtag : RESULT FAILED (no boot after $attempt attempts)"; }}
else {{
$boot = [math]::Round(((Get-Date) - $boot0).TotalSeconds, 1)
Log ("$rtag : booted in {{0}}s, idle settle..." -f $boot)
$after = Get-Process | Where-Object {{ $_.ProcessName -match '^(kjava|java)$' }} | Select-Object -ExpandProperty Id
$new = $after | Where-Object {{ $before -notcontains $_ }}
if (-not $new) {{ $new = $after }}
$proc = Get-Process -Id $new[0]
Start-Sleep -Seconds {settle}
$cpuVals = @()
for ($w = 0; $w -lt {cpu_windows}; $w++) {{
  $t1 = $proc.TotalProcessorTime; Start-Sleep -Seconds {cpu_window}; $proc.Refresh()
  $t2 = $proc.TotalProcessorTime
  $cpuVals += [math]::Round((($t2 - $t1).TotalSeconds / {cpu_window} / $cores) * 100, 1)
}}
$cpuIdle = [math]::Round(($cpuVals | Measure-Object -Average).Average, 1)
$rssI = @(); for ($i = 0; $i -lt {rss_n}; $i++) {{ $proc.Refresh(); $rssI += [math]::Round($proc.WorkingSet64 / 1MB); Start-Sleep -Seconds {rss_gap} }}
$rssIdle = [math]::Round(($rssI | Measure-Object -Average).Average)
$nbots = {bots}; if ($BotOverride -ne "") {{ $nbots = [int]$BotOverride }}
$staySecs = {stay}; if ($StayOverride -ne "") {{ $staySecs = [int]$StayOverride }}
# Scalar churn count (not an array): Start-Job -ArgumentList flattens a
# trailing array on PS 5.1, so "@churn" splatting was version-fragile.
# --churn-cycles is OMITTED for non-churn behaviors: argparse needs an int,
# so passing an empty string broke EVERY non-churn bot (found 2026-09-13:
# WI-6 rerun RESULT ERROR "usage: load-bot.py" on crowd). Churn bots pass
# the scalar; everyone else takes the bot-side default.
$churnFlag = ""; if ('{behavior}' -eq 'churn') {{ $churnFlag = "--churn-cycles {churnN}" }}
# Short names: "B"+behavior+n ("Bchurn1_c3" = 10 chars, was "Benchchurn1_c3" = 14).
$valid = $true
if ($nbots -gt 0) {{
  Log ("$rtag : idle cpu={{0}}% rss={{1}}MB, starting {{2}}x{behavior} bots..." -f $cpuIdle, $rssIdle, $nbots)
  $jobs = @()
  for ($b = 1; $b -le $nbots; $b++) {{
    $seed = (($b * 13 + $rep * 29) % 97)
    $jobs += Start-Job -ScriptBlock {{ param($port,$n,$stay,$beh,$seed,$churnFlag) Invoke-Expression "python C:\Users\bench\bench\load-bot.py --port $port --name B$beh$n --stay $stay --behavior $beh --seed $seed $churnFlag" }} -ArgumentList {port},$b,$staySecs,'{behavior}',$seed,$churnFlag
  }}
  Start-Sleep -Seconds 15
  $cpuVals2 = @()
  for ($w = 0; $w -lt {cpu_windows}; $w++) {{
    $t1 = $proc.TotalProcessorTime; Start-Sleep -Seconds {cpu_window}; $proc.Refresh()
    $t2 = $proc.TotalProcessorTime
    $cpuVals2 += [math]::Round((($t2 - $t1).TotalSeconds / {cpu_window} / $cores) * 100, 1)
  }}
  $cpuLoad = [math]::Round(($cpuVals2 | Measure-Object -Average).Average, 1)
  $rssL = @(); for ($i = 0; $i -lt {rss_n}; $i++) {{ $proc.Refresh(); $rssL += [math]::Round($proc.WorkingSet64 / 1MB); Start-Sleep -Seconds {rss_gap} }}
  $rssLoad = [math]::Round(($rssL | Measure-Object -Average).Average)
  # PS 5.1-compatible wait (Receive-Job has no -Timeout/-AutoRemoveJob there).
  # Timeout derives from the stay window + measurement windows + margin, so
  # long scenarios (soak: stay 1800) are not cut off at a hardcoded 300s.
  $jobTimeout = $staySecs + {cpu_windows} * {cpu_window} + {rss_n} * {rss_gap} + 120
  $null = Wait-Job $jobs -Timeout $jobTimeout
  # Per-job completion states (job objects lack exit codes for external
  # python; Completed vs Failed/Stopped/Running is the signal we keep).
  $botStates = @($jobs | ForEach-Object {{ $_.State }})
  $botLog = Receive-Job $jobs 2>&1 | Out-String
  $stuck = $jobs | Where-Object {{ $_.State -eq 'Running' }}
  if ($stuck) {{ $stuck | Stop-Job; $jobs | Remove-Job -Force; Log "$rtag : WARN (bot jobs timed out after $jobTimeout s, partial log)" }}
  else {{ $jobs | Remove-Job -Force }}
  $nOk = @($botStates | Where-Object {{ $_ -eq 'Completed' }}).Count
  $nBad = $nbots - $nOk
  # Count distinct bots ("bot done" prints once per bot) instead of
  # "entered play" (churn bots print it once per reconnect cycle).
  # For churn also count total reconnect cycles ("churn done cycles=N").
  $joins = ([regex]::Matches($botLog, 'bot done')).Count
  $cycles = 0; foreach ($m in [regex]::Matches($botLog, 'churn done cycles=(\d+)')) {{ $cycles += [int]$m.Groups[1].Value }}
  $jlats = @(); foreach ($m in [regex]::Matches($botLog, 'join=([0-9.]+)s')) {{ $jlats += [double]$m.Groups[1].Value }}
  if ($jlats.Count -gt 0) {{ $joinAvg = [math]::Round(($jlats | Measure-Object -Average).Average, 1) }} else {{ $joinAvg = 'n/a' }}
  $botNote = "bots ok=$nOk failed=$nBad"
  Log "$rtag : $botNote"
  if ($joins -eq 0) {{ $valid = $false; Log "$rtag : INVALID (0 bots joined; load windows already ran, only recording skipped)" }}
  elseif ($nBad -gt 0) {{ Log "$rtag : WARN ($nBad of $nbots bot jobs did not complete cleanly)" }}
}} else {{
  $cpuLoad = 'n/a'; $rssLoad = 'n/a'; $joins = 'n/a'; $joinAvg = 'n/a'
  Log ("$rtag : idle cpu={{0}}% rss={{1}}MB (no bots)" -f $cpuIdle, $rssIdle)
}}
if ($proc -ne $null) {{ Stop-Process -Id $proc.Id -Force }}
Start-Sleep -Seconds 3
if ($valid) {{
  $cycTxt = ""; if ('{behavior}' -eq 'churn') {{ $cycTxt = " cycles=$cycles" }}
  $res = "$rtag : RESULT boot={{0}}s cpuIdle={{1}}% rssIdle={{2}}MB cpuLoad={{3}} rssLoad={{4}}MB joinAvg={{5}}s joins={{6}}$cycTxt" -f $boot, $cpuIdle, $rssIdle, $cpuLoad, $rssLoad, $joinAvg, "$joins/$nbots"
}} else {{
  $res = ("$rtag : RESULT INVALID boot={{0}}s joins=0/" + $nbots + " (load data discarded)") -f $boot
}}
Log $res; Write-Output $res
if ($valid) {{
  $repResults += [pscustomobject]@{{ boot_s=$boot; cpu_idle=$cpuIdle; rss_idle_mb=$rssIdle; cpu_load=$cpuLoad; rss_load_mb=$rssLoad; join_avg_s="$joinAvg"; joins="$joins/$nbots" }}
  $summary += [pscustomobject]@{{ run="$rtag"; boot_s=$boot; cpu_idle=$cpuIdle; rss_idle_mb=$rssIdle; cpu_load="$cpuLoad"; rss_load_mb="$rssLoad"; join_avg_s="$joinAvg"; joins="$joins/$nbots" }}
  SaveJson
}}
}}
}} catch {{
  Log "$rtag : RESULT ERROR $($_.Exception.Message)"
}}
}} # rep loop
if ($repResults.Count -gt 1) {{
  # [Math]::Floor, not [int]() (which does banker's rounding: [int]1.5 = 2).
  function Get-Med($xs) {{ $s = @($xs | Sort-Object); $n = $s.Count; if ($n % 2 -eq 1) {{ $s[[Math]::Floor($n/2)] }} else {{ [math]::Round(($s[$n/2-1]+$s[$n/2])/2,1) }} }}
  # 'n/a' sentinels (zero-bot scenarios) cannot cast to [double]; drop them.
  function Nums($xs) {{ @($xs | Where-Object {{ $_ -ne 'n/a' }} | ForEach-Object {{ [double]$_ }}) }}
  $mBoot = Get-Med @($repResults | ForEach-Object {{ $_.boot_s }})
  $mCpuI = Get-Med @($repResults | ForEach-Object {{ $_.cpu_idle }})
  $mRssI = Get-Med @($repResults | ForEach-Object {{ $_.rss_idle_mb }})
  $mCpuL = Get-Med (Nums @($repResults | ForEach-Object {{ $_.cpu_load }}))
  $mRssL = Get-Med (Nums @($repResults | ForEach-Object {{ $_.rss_load_mb }}))
  $mRes = "{tag}: MEDIAN over $($repResults.Count) reps boot={{0}}s cpuIdle={{1}}% rssIdle={{2}}MB cpuLoad={{3}}% rssLoad={{4}}MB" -f $mBoot, $mCpuI, $mRssI, $mCpuL, $mRssL
  Log $mRes; Write-Output $mRes
}}
}}
'''


def load_config(path):
    with open(path) as f:
        return yaml.safe_load(f)


def script_for(server_cfg, flag):
    # vanilla-RUN.bat -> vanilla-run.bat / vanilla-tuned.bat
    base = server_cfg["start_script"]
    if "-RUN" in base:
        return base.replace("-RUN", "-run" if flag == "default" else "-tuned")
    if "RUN" in base:
        return base.replace("RUN", "run" if flag == "default" else "tuned")
    return base


def generate(cfg, mode, only=(), servers=(), flags=()):
    samp = cfg["sampling"][mode]
    blocks = []
    for server in cfg["matrix"]["servers"]:
        if servers and server not in servers:
            continue
        scfg = cfg["servers"][server]
        for flag in cfg["matrix"]["flag_sets"]:
            if flags and flag not in flags:
                continue
            for scenario in cfg["matrix"]["scenarios"]:
                if only and scenario not in only:
                    continue
                scen = cfg["scenarios"][scenario]
                scen_samp = scen.get("sampling", None)
                s = cfg["sampling"].get(scen_samp, samp) if scen_samp else samp
                tag = f"{server.upper()}-{flag.upper()}-{scenario.upper()}"
                stay = max(int(scen.get("stay_s", 0)),
                           15 + s["cpu_window_s"] * s["cpu_windows"]
                           + s["rss_samples"] * s["rss_gap_s"] + 10)
                blocks.append(RUN_BLOCK.format(
                    tag=tag, scenario=scenario, server=server, flag=flag,
                    script=script_for(scfg, flag), log=scfg["log"],
                    pattern=scfg["ready_pattern"], port=scfg["port"],
                    ready_timeout=cfg["meta"].get("ready_timeout_s", 180),
                    retries=int(cfg["meta"].get("boot_retries", 1)),
                    settle=s["idle_settle_s"], cpu_window=s["cpu_window_s"],
                    cpu_windows=s["cpu_windows"], rss_n=s["rss_samples"],
                    rss_gap=s["rss_gap_s"], bots=int(scen.get("bot_count", 0)),
                    behavior=scen.get("behavior", "idle"), stay=stay,
                    repeats=int(scen.get("repeats", 1)),
                    churnN=int(scen.get("churn_cycles", 4))))
    out = cfg["output"]
    # Protocol match: the bot hardcodes PROTOCOL; bench.yaml declares
    # meta.protocol. A 26.x bump that updates one but not the other would
    # silently bench bots that can never log in.
    import re as _re
    _td = "harness/tools/" if __import__("os").path.isdir("harness/tools") else "tools/"
    try:
        bot_src = open(_td + "load-bot.py").read()
        bot_proto = _re.search(r"^PROTOCOL\s*=\s*(\d+)", bot_src, _re.M).group(1)
    except (OSError, AttributeError):
        bot_proto = None
    yaml_proto = str(cfg["meta"].get("protocol", ""))
    if bot_proto is not None and bot_proto != yaml_proto:
        sys.exit(f"protocol mismatch: load-bot.py PROTOCOL={bot_proto} "
                 f"but bench.yaml meta.protocol={yaml_proto}")
    # Build identity stamped into the results header: repo SHA + per-server
    # start script + per-flag .bat mapping (WI-9 asserts the .bat contents).
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True).stdout.strip()
    except OSError:
        sha = "unknown"
    script_map = "; ".join(
        f"{s}={script_for(cfg['servers'][s], cfg['matrix']['flag_sets'][0])}"
        for s in cfg["matrix"]["servers"])
    flag_map = "; ".join(
        f"{f}->" + ", ".join(
            f"{s}:{script_for(cfg['servers'][s], f).split(chr(92))[-1]}"
            for s in cfg["matrix"]["servers"])
        for f in cfg["matrix"]["flag_sets"])
    build_id = (f"{datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')} "
                f"run-bench@{sha} proto={yaml_proto}")
    return PS_TEMPLATE.format(
        stamp=datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
        results_file=out["results_file"], json_file=out["json_file"],
        build_id=build_id, script_map=script_map, flag_map=flag_map,
        run_blocks="\n".join(blocks))


def sh(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="bench.yaml")
    ap.add_argument("--only", default="")
    ap.add_argument("--bots", default="")
    ap.add_argument("--repeats", default="")
    ap.add_argument("--stay", default="")
    ap.add_argument("--servers", default="")
    ap.add_argument("--flags", default="")
    ap.add_argument("--mode", default="fast",
                    choices=["fast", "quality", "soak"])
    ap.add_argument("--launch", action="store_true")
    ap.add_argument("--poll", action="store_true")
    args = ap.parse_args()

    cfg = load_config(args.config)

    if args.poll:
        rfile = cfg["output"]["results_file"]
        r = sh(["ssh", "-o", "ConnectTimeout=25", WINPC,
                f"pwsh -NoProfile -Command \"Get-Content {rfile}\""])
        print(r.stdout[-4000:] if len(r.stdout) > 4000 else r.stdout)
        return 0

    # Fail fast on filters that would silently generate zero runs.
    matrix_scens = cfg["matrix"]["scenarios"]
    if args.only:
        for name in args.only.split(","):
            if name not in matrix_scens:
                known = sorted(set(matrix_scens) | set(cfg["scenarios"].keys()))
                sys.exit(f"--only '{name}' is not in matrix.scenarios "
                         f"(defined scenarios: {', '.join(known)}). "
                         f"Note: 'soak' is defined but excluded from the matrix "
                         f"(30 min); run it via --only with an explicit matrix entry.")
    for cli, key in ((args.servers, "servers"), (args.flags, "flag_sets")):
        if cli:
            known = (cfg["matrix"][key] if key in cfg["matrix"]
                     else list(cfg[key].keys()))
            for name in cli.split(","):
                if name not in known:
                    sys.exit(f"--{key} '{name}' unknown (known: {', '.join(known)})")
    only = args.only.split(",") if args.only else ()
    servers = args.servers.split(",") if args.servers else ()
    flags = args.flags.split(",") if args.flags else ()
    ps = generate(cfg, args.mode, only=only, servers=servers, flags=flags)
    gen_path = "/tmp/bench_run.ps1"
    with open(gen_path, "w") as f:
        f.write(ps)
    import re as _re2
    n_runs = len(_re2.findall(r"# ---- \S+ ----", ps))
    print(f"generated {gen_path} ({n_runs} runs, mode={args.mode})")
    if not args.launch:
        print("dry run: pass --launch to copy + start detached on bench PC")
        return 0

    print("copying load-bot.py + bench_run.ps1 + launch-bench.ps1...")
    import os as _os
    _td = "harness/tools/" if _os.path.isdir("harness/tools") else "tools/"
    for local, remote in [(_td + "load-bot.py", "load-bot.py"),
                          (gen_path, "bench_run.ps1"),
                          (_td + "launch-bench.ps1", "launch-bench.ps1")]:
        r = sh(["scp", "-o", "ConnectTimeout=15",
                local, f"{WINPC}:C:/Users/bench/bench/{remote}"])
        if r.returncode != 0:
            sys.exit(f"scp {remote} failed: {r.stderr[-500:]}")
    # WI-9 assert-match: the YAML jvm_flags are decorative unless the
    # resolved bench PC .bat actually contains them. Check over SSH before
    # launching so a hand-edited .bat (or a YAML typo) fails loudly
    # instead of silently benching the wrong JVM flags.
    _need = {}
    for _srv in cfg["matrix"]["servers"]:
        for _flg in cfg["matrix"]["flag_sets"]:
            _bat = script_for(cfg["servers"][_srv], _flg)
            for _tok in cfg["flag_sets"][_flg].get("jvm_flags", "").split():
                _need.setdefault(_bat, set()).add(_tok)
    for _bat, _toks in sorted(_need.items()):
        _r = sh(["ssh", "-o", "ConnectTimeout=25", WINPC, "pwsh",
                 "-NoProfile", "-Command",
                 f"(Get-Content '{_bat}' -Raw)"])
        if _r.returncode != 0:
            sys.exit(f"flag assert: cannot read {_bat}: {_r.stderr[-300:]}")
        _missing = [t for t in sorted(_toks) if t not in _r.stdout]
        if _missing:
            sys.exit(f"flag assert: {_bat} lacks YAML jvm_flags "
                     f"{', '.join(_missing)} (yaml="
                     f"{ {f: cfg['flag_sets'][f].get('jvm_flags', '') for f in cfg['matrix']['flag_sets']} })")
    extra = ""
    if args.only:
        extra += f" -Only {args.only}"
    if args.servers:
        extra += f" -Servers {args.servers}"
    if args.flags:
        extra += f" -Flags {args.flags}"
    if args.bots:
        extra += f" -BotOverride {args.bots}"
    if args.repeats:
        extra += f" -RepeatOverride {args.repeats}"
    if args.stay:
        extra += f" -StayOverride {args.stay}"
    with open("/tmp/launch_cmd.sh", "w") as f:
        f.write("#!/bin/bash\n"
                "ssh -o ConnectTimeout=30 "
                + WINPC +
                " 'pwsh -NoProfile -ExecutionPolicy Bypass "
                "-File C:\\Users\\bench\\bench\\launch-bench.ps1"
                + extra + "'\n")
    import os
    os.chmod("/tmp/launch_cmd.sh", 0o755)
    r = sh(["/tmp/launch_cmd.sh"])
    out = (r.stdout + r.stderr)[-300:]
    print("launcher output:", out)
    if "DETACHED" not in out:
        sys.exit("launch failed: no DETACHED confirmation")
    print("detached run started. poll with: python3 tools/run-bench.py --poll")
    return 0


if __name__ == "__main__":
    sys.exit(main())
